        Rule("reconciliation", null, listOf("διορθωση", "τακτοποιηση", "reconciliation", "adjustment")),
    )

    private fun decode(value: String): Pair<String, String> {
        val prefix = value.substringBefore(':')
        return if (prefix in packs && ':' in value) prefix to value.substringAfter(':')
        else "lucide" to value
    }

    private fun reference(pack: String, key: String): String? {
        if (pack !in packs) return null
        val name = if (catalogKey.matches(key)) key.removePrefix("icon/") else semantic[pack]?.get(key)
        return name?.let { "$pack:$it" }
    }

    /** Explicit per-pack selection wins; legacy values apply only to their pack. */
    fun explicit(pack: String?, legacy: String?, remembered: Map<String, String>?): String? {
        if (pack == null) return legacy?.let { decode(it) }.let { decoded ->
            decoded?.let { reference(it.first, it.second) }
        }
        val active = pack.takeIf { it in packs } ?: "lucide"
        val selected = remembered?.get(active)?.let { decode(it).second }
        reference(active, selected.orEmpty())?.let { return it }
        val decoded = legacy?.let(::decode) ?: return null
        return if (decoded.first == active) reference(active, decoded.second) else null
    }

    private fun normalized(value: String) = Normalizer.normalize(value, Normalizer.Form.NFD)
        .replace(Regex("\\p{M}+"), "").lowercase(Locale.forLanguageTag("el-GR"))
        .replace(Regex("[^a-z0-9α-ω]+"), " ").trim()

    private fun infer(kind: String, label: String?): String? {
        val value = normalized(label.orEmpty())
        if (value.isBlank()) return null
        return rules.firstOrNull { rule ->
            (rule.kind == null || rule.kind == kind) && rule.terms.any { value.contains(normalized(it)) }
        }?.key ?: if (value in setOf("αλλο", "αλλα", "other", "misc"))
            if (kind == "income") "income" else "other" else null
    }

    /** Activity inherits explicit child -> explicit parent, then inferred child -> parent.
     * Every key is a local catalog identifier, never a path or external URL. */
    fun candidates(kind: String, category: String?, subcategory: String?, pack: String,
                   explicit: Map<String, String>): List<String> {
        val parent = category?.trim()?.takeIf(String::isNotEmpty) ?: return emptyList()
        val type = if (kind == "income") "income" else "expense"
        val base = "$type:$parent"
        val child = subcategory?.trim()?.takeIf(String::isNotEmpty)
        return listOfNotNull(
            child?.let { explicit["$base:$it"] },
            explicit[base],
            infer(type, child)?.let { reference(pack, it) },
            infer(type, parent)?.let { reference(pack, it) },
        ).distinct()
    }
}
